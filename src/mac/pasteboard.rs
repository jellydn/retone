//! Pasteboard snapshot and restore for the ⌘C / ⌘V fallback.
//!
//! The snapshot lives in memory only. Restore runs only when the pasteboard's `changeCount` is
//! still the value Retone wrote, so a newer copy by the user is never overwritten.

use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardWriting};
use objc2_foundation::{NSArray, NSData, NSString};

/// Above this total size the snapshot is marked incomplete; restoring part of a clipboard is worse
/// than asking the user first.
pub const SNAPSHOT_LIMIT_BYTES: usize = 16 * 1024 * 1024;

/// Marker types from nspasteboard.org: clipboard managers skip items that carry them.
const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
const AUTO_GENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";
const PLAIN_TEXT_TYPE: &str = "public.utf8-plain-text";
const DERIVED_TEXT_TYPES: [&str; 3] =
    ["public.utf16-external-plain-text", "public.utf16-plain-text", "com.apple.traditional-mac-plain-text"];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Snapshot {
    /// One entry per pasteboard item: every type with its bytes, in the original order.
    pub items: Vec<Vec<(String, Vec<u8>)>>,
    pub change_count: isize,
    /// False when a type gave no data (promised or lazy data) or the size limit was reached.
    pub complete: bool,
}

/// A pasteboard handle: the general one in the app, a uniquely named one in tests.
pub struct Board {
    pasteboard: Retained<NSPasteboard>,
    unique: bool,
}

impl Board {
    pub fn general() -> Self {
        Self { pasteboard: NSPasteboard::generalPasteboard(), unique: false }
    }

    /// A private pasteboard that no other app reads; released when dropped.
    #[cfg(test)]
    pub fn unique() -> Self {
        Self { pasteboard: NSPasteboard::pasteboardWithUniqueName(), unique: true }
    }

    pub fn change_count(&self) -> isize {
        self.pasteboard.changeCount()
    }

    pub fn snapshot(&self) -> Snapshot {
        let change_count = self.change_count();
        let mut items = Vec::new();
        let mut complete = true;
        let mut total = 0usize;
        for item in self.pasteboard.pasteboardItems().iter().flat_map(|items| items.to_vec()) {
            let kinds: Vec<String> = item.types().to_vec().iter().map(|kind| kind.to_string()).collect();
            let has_utf8 = kinds.iter().any(|kind| kind == PLAIN_TEXT_TYPE);
            let mut entries = Vec::new();
            for kind in kinds {
                // macOS makes these from the item's other text on request (from the RTF, in the
                // S3 spike), so their bytes can differ from the UTF-8 text. Restoring the UTF-8
                // lets macOS make them again from the right source.
                if has_utf8 && DERIVED_TEXT_TYPES.contains(&kind.as_str()) {
                    continue;
                }
                let Some(data) = item.dataForType(&NSString::from_str(&kind)) else {
                    complete = false;
                    continue;
                };
                total += data.length();
                if total > SNAPSHOT_LIMIT_BYTES {
                    complete = false;
                    break;
                }
                entries.push((kind, data.to_vec()));
            }
            items.push(entries);
        }
        Snapshot { items, change_count, complete }
    }

    /// Writes the snapshot back. Returns the new `changeCount`.
    pub fn restore(&self, snapshot: &Snapshot) -> isize {
        let items: Vec<Retained<NSPasteboardItem>> = snapshot
            .items
            .iter()
            .map(|entries| {
                let item = NSPasteboardItem::new();
                for (kind, bytes) in entries {
                    item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(kind));
                }
                item
            })
            .collect();
        self.write_items(&items)
    }

    /// Restores only if nobody wrote to the pasteboard since Retone's own write.
    pub fn restore_if_unchanged(&self, snapshot: &Snapshot, retone_change_count: isize) -> bool {
        if self.change_count() != retone_change_count {
            return false;
        }
        self.restore(snapshot);
        true
    }

    /// Writes text marked transient, for the ⌘V fallback. Returns the new `changeCount`.
    pub fn write_transient_text(&self, text: &str) -> isize {
        let item = NSPasteboardItem::new();
        item.setData_forType(&NSData::with_bytes(text.as_bytes()), &NSString::from_str(PLAIN_TEXT_TYPE));
        for marker in [TRANSIENT_TYPE, AUTO_GENERATED_TYPE] {
            item.setData_forType(&NSData::new(), &NSString::from_str(marker));
        }
        self.write_items(&[item])
    }

    /// Reads plain text, for the ⌘C fallback and clipboard-only mode.
    pub fn text(&self) -> Option<String> {
        self.pasteboard.stringForType(&NSString::from_str(PLAIN_TEXT_TYPE)).map(|text| text.to_string())
    }

    fn write_items(&self, items: &[Retained<NSPasteboardItem>]) -> isize {
        self.pasteboard.clearContents();
        let writers: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> =
            items.iter().map(|item| ProtocolObject::from_retained(item.clone())).collect();
        self.pasteboard.writeObjects(&NSArray::from_retained_slice(&writers));
        self.change_count()
    }
}

impl Drop for Board {
    fn drop(&mut self) {
        if self.unique {
            // objc2-app-kit skips `releaseGlobally` in its bindings, so call it directly.
            // SAFETY: `releaseGlobally` takes no arguments, returns void, and is sent to a live
            // NSPasteboard that this Board owns; nothing uses the pasteboard after this point.
            unsafe { objc2::msg_send![&*self.pasteboard, releaseGlobally] }
        }
    }
}

